import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {register} from '../lib/vercel-auth-store.mjs';
import {CloudClient} from './cloud-client.mjs';
if(process.env.ARENA_ALLOW_CLOUD_SMOKE!=='1')throw Error('Explicit cloud demo opt-in required');
const base='https://oan-tu-ti-ai-arena.vercel.app',admin=new CloudClient(base),student=new CloudClient(base);
const credentials=JSON.parse(readFileSync(process.env.ARENA_CLOUD_ADMIN_FILE||'.secrets/vercel-demo-admin.json','utf8'));
await admin.login(credentials.email,credentials.password);
const tag=randomBytes(4).toString('hex'),email=`demo-join-${tag}@vnu.edu.vn`,password=randomBytes(18).toString('base64url');
// Provision a labeled fixture directly; this never sends a confirmation email.
await register({email,name:'Demo sinh viên · tham gia trực tiếp',password});
await student.login(email,password);
const event=(await admin.post({action:'create',name:'DEMO · kiểm tra xoá và khôi phục '+tag,config:{entryMode:'invite',groupCount:1,qualifiers:2,deadline:new Date(Date.now()+86400000).toISOString(),maxPlies:20},openNow:true})).id;
writeFileSync('.secrets/tournament-trash-cloud.json',JSON.stringify({event,email,password,base},null,2));
const open=await student.call('/api/competition?event='+event);assert.equal(open.event.openEntry,true);assert.equal(open.event.config.entryMode,'invite');
const joined=await student.post({action:'join_open',event});
assert.ok(joined.team);assert.equal((await student.call('/api/competition?event='+event)).user.admin,false);
const submitted=await student.post({action:'submit',event,source:'def choose_move(state):\n return state["legal_moves"][0]\n'});
await student.post({action:'archive',event},403);
await admin.post({action:'archive',event});
await student.call('/api/competition?event='+event,undefined,404);
assert.ok(!(await admin.call('/api/competition')).events.some(e=>e.id===event));
assert.ok((await admin.call('/api/competition')).archivedEvents.some(e=>e.id===event));
assert.ok(!(await student.call('/api/portal')).teams.some(t=>t.event===event));
await student.post({action:'restore',event},403);
await admin.post({action:'restore',event});
const restored=await student.call('/api/competition?event='+event);assert.equal(restored.owned,joined.team);assert.equal(restored.event.paused,1);assert.ok(restored.submissions.some(s=>s.id===submitted.id));
assert.ok((await student.call('/api/competition?submission='+submitted.id)).source.includes('choose_move'));
await admin.post({action:'archive',event});
const proof={at:new Date().toISOString(),site:base,event,codeFreeLegacyEnrollment:true,adminRoleUnchanged:true,unauthorizedArchiveAndRestoreRejected:true,archiveHidesEventAndMembership:true,restorePreservesTeamAndSource:true,restoredJudgingPaused:true,fixtureLeftInTrash:true};
writeFileSync('docs/submission/evidence/tournament-trash-cloud.json',JSON.stringify(proof,null,2)+'\n');console.log(proof);
