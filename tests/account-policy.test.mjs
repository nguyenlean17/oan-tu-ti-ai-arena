import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { isValidEmail, accountAllowed } from '../lib/account-policy.mjs';
import { register as cloudRegister } from '../lib/vercel-auth-store.mjs';
import { authPage } from '../docker/auth-view.mjs';
import { openStore, register, authenticate, sessionUser, newSession, createPasswordReset, resetPassword } from '../docker/auth-store.mjs';
assert.ok(isValidEmail(' Student.01@Example.COM '));
assert.ok(isValidEmail('student@vnu.edu.vn'));
for (const email of ['not-an-email','a@','a\n@example.com','.a@example.com','a..b@example.com','a.@example.com']) assert.equal(isValidEmail(email),false,email);
assert.ok(accountAllowed({email:'btc@example.test',is_admin:1}));
assert.equal(accountAllowed({email:'btc@example.test',is_admin:0}),true);
assert.equal(accountAllowed({email:'btc@example.test',is_admin:0,disabled:1}),false);
assert.equal(accountAllowed(null),false);
await assert.rejects(() => cloudRegister({email:'not-an-email',password:'not-used'}), {status:400});
const directory=mkdtempSync(path.join(tmpdir(),'uet-policy-')),db=openStore(directory);
try {
  const password='Test-password-123456';
  const user=await register(db,{email:' Student@Example.COM ',name:'Student',phone:'0123456789',password});
  assert.equal(user.email,'student@example.com');
  assert.equal((await authenticate(db,'STUDENT@EXAMPLE.COM',password)).id,user.id);
  assert.equal(await authenticate(db,user.email,'incorrect-password'),null);
  assert.equal(sessionUser(db,newSession(db,user.id)).id,user.id);
  await assert.rejects(() => register(db,{email:'bad-email',password}), {status:400});
  db.prepare('UPDATE users SET email=? WHERE id=?').run('legacy@example.test',user.id);
  const oldSession=newSession(db,user.id);
  assert.equal(sessionUser(db,oldSession).id,user.id);
  assert.equal((await authenticate(db,'legacy@example.test',password)).id,user.id);
  db.prepare('UPDATE users SET disabled=1 WHERE id=?').run(user.id);
  assert.equal(sessionUser(db,oldSession),null);
  assert.equal(await authenticate(db,'legacy@example.test',password),null);
  db.prepare('UPDATE users SET disabled=0 WHERE id=?').run(user.id);
  assert.equal((await authenticate(db,'legacy@example.test',password)).id,user.id);
  assert.equal(sessionUser(db,oldSession).id,user.id);
  const resetToken=createPasswordReset(db,user.id);
  await resetPassword(db,resetToken,'New-password-123456');
  assert.equal(await authenticate(db,'legacy@example.test',password),null);
  assert.equal((await authenticate(db,'legacy@example.test','New-password-123456')).id,user.id);
  assert.equal(sessionUser(db,oldSession),null);
  await assert.rejects(()=>resetPassword(db,resetToken,'Another-password-123456'),{status:400});
  const html=authPage({mode:'register',csrf:'test',returnTo:'/competition'});
  assert.doesNotMatch(html,/@vnu\.edu\.vn/); assert.match(html,/Không gửi mã xác nhận/); assert.match(html,/Số điện thoại/);
  console.log('Email policy passed: public email domains, normalization, invalid address rejection, disabled account sessions, passwords and registration UI.');
} finally { db.close(); rmSync(directory,{recursive:true,force:true}); }
