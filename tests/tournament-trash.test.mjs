import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {openCompetition,action,overview,leaseJob,finishJob,heartbeat,submissionSource,RUNTIME_VERSION} from '../competition/store.mjs';
import {authPage} from '../docker/auth-view.mjs';
import {ENGINE_VERSION} from '../lib/engine.mjs';
const directory=mkdtempSync(path.join(tmpdir(),'arena-trash-')),db=openCompetition(directory);
const admin={id:'btc',email:'btc@vnu.edu.vn',is_admin:1},alice={id:'alice',email:'alice@vnu.edu.vn',name:'Alice'},bob={id:'bob',email:'bob@vnu.edu.vn'};
const config={entryMode:'invite',groupCount:1,qualifiers:2,deadline:new Date(Date.now()+86400000).toISOString()};
try{
 delete process.env.ARENA_LOAD_DEMO;delete process.env.DEMO_SELF_SERVICE;delete process.env.DEMO_OPEN_ENTRY;
 const event=(await action(db,admin,{action:'create',name:'Trash test',config,openNow:true})).id;
 await assert.rejects(()=>action(db,alice,{action:'join_open',event}),e=>e.status===403);
 process.env.DEMO_OPEN_ENTRY='1';
 assert.match(authPage({mode:'login',csrf:'test',returnTo:'/competition'}),/không cần mã BTC/);
 const before=await overview(db,alice,event);assert.equal(before.event.openEntry,true);assert.equal(before.event.config.entryMode,'invite','Presentation policy must not rewrite stored rules');
 await assert.rejects(()=>action(db,alice,{action:'create',name:'No role escalation',config}),e=>e.status===403);
 await action(db,alice,{action:'join_open',event});
 const submission=await action(db,alice,{action:'submit',event,source:'def choose_move(state):\n return state["legal_moves"][0]\n'});
 const job=await leaseJob(db,'worker',RUNTIME_VERSION);assert.ok(job);
 await assert.rejects(()=>action(db,alice,{action:'archive',event}),e=>e.status===403);
 await action(db,admin,{action:'archive',event});await action(db,admin,{action:'archive',event});
 assert.ok(!(await overview(db,admin)).events.some(e=>e.id===event));
 assert.ok((await overview(db,admin)).archivedEvents.some(e=>e.id===event));
 assert.deepEqual((await overview(db,alice)).archivedEvents,[]);
 await assert.rejects(()=>overview(db,admin,event),e=>e.status===404);
 await assert.rejects(()=>action(db,bob,{action:'join_open',event}),e=>e.status===404);
 await assert.rejects(()=>heartbeat(db,'worker',job.id,job.lease),e=>e.status===409);
 await assert.rejects(()=>finishJob(db,'worker',job.id,job.lease,{valid:true,message:'ok',sha:job.payload.sha,engine:ENGINE_VERSION,runtime:RUNTIME_VERSION}),e=>e.status===409);
 assert.equal(await leaseJob(db,'worker',RUNTIME_VERSION),null);
 assert.ok((await submissionSource(db,alice,submission.id)).source.includes('choose_move'));
 await assert.rejects(()=>action(db,bob,{action:'restore',event}),e=>e.status===403);
 await action(db,admin,{action:'restore',event});
 const restored=await overview(db,alice,event);assert.equal(restored.event.status,'open');assert.equal(restored.event.paused,1);assert.equal(restored.submissions[0].id,submission.id);assert.ok(restored.owned);
 assert.equal(await leaseJob(db,'worker',RUNTIME_VERSION),null);
 await action(db,admin,{action:'pause',event});const fresh=await leaseJob(db,'worker',RUNTIME_VERSION);assert.ok(fresh);assert.notEqual(fresh.lease,job.lease);assert.equal(db.prepare('SELECT attempts FROM jobs WHERE id=?').get(fresh.id).attempts,1);
 delete process.env.DEMO_OPEN_ENTRY;
 assert.equal((await overview(db,bob,event)).event.openEntry,false);
 await assert.rejects(()=>action(db,bob,{action:'join_open',event}),e=>e.status===403);
 console.log('Trash/open demo passed: scoped permissions, reversible data, lease fencing, paused restore, code-free joining and no admin escalation.');
}finally{db.close();rmSync(directory,{recursive:true,force:true});delete process.env.DEMO_OPEN_ENTRY;}
