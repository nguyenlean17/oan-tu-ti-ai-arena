import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { CloudClient } from './cloud-client.mjs';
if (process.env.ARENA_ALLOW_LOAD_TEST !== '1') throw new Error('Explicit opt-in required; this test uses the isolated localhost:3002 stack');
const base = 'http://localhost:3002', fixture = JSON.parse(readFileSync('.secrets/load-fixtures.json', 'utf8'));
const admin = new CloudClient(base), student = new CloudClient(base), outsideTeam = new CloudClient(base);
await admin.login(fixture.admin.email, fixture.admin.password);
student.jar.set('arena_session', fixture.users[0].token); outsideTeam.jar.set('arena_session', fixture.users.at(-1).token);
assert.equal((await fetch(base + '/api/operations')).status, 401);
assert.equal((await fetch(base + '/api/operations?view=demo')).status, 200, 'Read-only demo is enabled only by the dedicated compose profile');
assert.equal((await fetch(base + '/operations', { redirect: 'manual' })).status, 307);
assert.equal((await fetch(base + '/load-demo')).status, 200);
await student.call('/api/operations', undefined, 403);
await student.call('/api/operations', { action: 'selftest' }, 403);
await student.call('/api/operations', { action: 'review', event: fixture.tournament }, 403);
await student.call('/api/operations', { action: 'practice_submit', source: null }, 400);
await student.call('/api/operations', { action: 'practice_submit', source: 'a'.repeat(65537) }, 400);
const cross = await fetch(base + '/api/operations', { method: 'POST', headers: { Cookie: admin.cookies(), Origin: 'https://attacker.invalid', 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'selftest' }) });
assert.equal(cross.status, 403);
const own = await student.call('/api/operations?view=queue&event=' + fixture.tournament);
assert.ok(own.submissions.length > 0);
const denied = await outsideTeam.call('/api/operations?view=queue&event=' + fixture.tournament);
assert.equal(denied.submissions.length, 0, 'Students outside a team must not see its submission status');
const practice = await student.call('/api/operations?view=practice');
assert.ok(!JSON.stringify(practice).includes('def choose_move'), 'Practice views never disclose source');
const metrics = await admin.call('/api/operations');
assert.ok(metrics.readiness.database && metrics.readiness.worker);
console.log('Operations HTTP passed: private admin views, demo read-only, CSRF, owner queue isolation, UTF-8 size limits and source confidentiality.');
