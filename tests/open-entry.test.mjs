import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {openCompetition,action,overview,exportEvent,submissionSource} from '../competition/store.mjs';
const directory=mkdtempSync(path.join(tmpdir(),'arena-open-')),db=openCompetition(directory);
const alice={id:'reviewer-a',name:'Alice',email:'alice@example.test',is_admin:0},bob={id:'reviewer-b',name:'Bob',email:'bob@example.test',is_admin:0};
const config={entryMode:'open',groupCount:1,qualifiers:2,deadline:new Date(Date.now()+86400000).toISOString(),maxPlies:20};
const denied=fn=>assert.rejects(fn,e=>e.status===403);
try{
 delete process.env.ARENA_LOAD_DEMO;process.env.DEMO_SELF_SERVICE='1';
 await denied(()=>action(db,alice,{action:'create',name:'Not a demo',config}));
 process.env.ARENA_LOAD_DEMO='1';
 const event=(await action(db,alice,{action:'create',name:'Reviewer tournament',config,openNow:true,owner:bob.id})).id;
 assert.equal((await overview(db,alice,event)).event.status,'open');
 assert.equal((await overview(db,alice,event)).canManage,true);
 assert.equal((await overview(db,alice,event)).user.admin,false);
 assert.equal((await overview(db,bob,event)).canManage,false);
 assert.ok((await overview(db,alice)).managedEvents.includes(event));
 for(const operation of ['pause','freeze','config','revoke','publish','demo_bots','close_demo'])await denied(()=>action(db,bob,{action:operation,event,config,user:alice.id}));
 await denied(()=>exportEvent(db,bob,event));
 const joined=await Promise.all(Array.from({length:8},()=>action(db,alice,{action:'join_open',event,user:bob.id})));
 assert.ok(joined.every(r=>r.team===joined[0].team));
 assert.equal(db.prepare('SELECT COUNT(*) n FROM teams WHERE event=?').get(event).n,1);
 assert.equal(db.prepare('SELECT user FROM members WHERE event=?').get(event).user,alice.id);
 await action(db,bob,{action:'join_open',event});
 assert.equal(db.prepare('SELECT COUNT(DISTINCT seed) n FROM teams WHERE event=?').get(event).n,2);
 const submitted=await action(db,alice,{action:'submit',event,source:'def choose_move(state):\n return state["legal_moves"][0]\n'});
 assert.ok((await submissionSource(db,alice,submitted.id)).source.includes('choose_move'));
 await assert.rejects(()=>submissionSource(db,null,submitted.id),e=>e.status===401);
 await assert.rejects(()=>submissionSource(db,bob,submitted.id),e=>e.status===404);
 await assert.rejects(()=>submissionSource(db,{id:'impersonator',email:alice.email},submitted.id),e=>e.status===404);
 await action(db,alice,{action:'demo_bots',event});await action(db,alice,{action:'demo_bots',event});
 assert.equal(db.prepare('SELECT COUNT(*) n FROM teams WHERE event=?').get(event).n,4);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM jobs WHERE event=?').get(event).n,3);
 assert.equal((await action(db,alice,{action:'close_demo',event})).waiting,true);
 assert.equal((await overview(db,alice,event)).event.status,'locking');
 const empty=(await action(db,alice,{action:'create',name:'Empty rollback test',config,openNow:true})).id;
 await assert.rejects(()=>action(db,alice,{action:'close_demo',event:empty}),e=>e.status===400);
 assert.equal((await overview(db,alice,empty)).event.config.deadline,config.deadline,'Failed close rolls back deadline');
 const inviteOnly=(await action(db,alice,{action:'create',name:'Closed roster',config:{...config,entryMode:'invite'},openNow:true})).id;
 await denied(()=>action(db,bob,{action:'join_open',event:inviteOnly}));
 const other=(await action(db,bob,{action:'create',name:'Bobs own event',config,openNow:true})).id;
 await denied(()=>action(db,alice,{action:'pause',event:other}));
 db.prepare("UPDATE events SET status='groups' WHERE id=?").run(event);
 await assert.rejects(()=>action(db,{id:'late-user',name:'Late'},{action:'join_open',event}),e=>e.status===409);
 console.log('Open-entry passed: demo isolation, event ownership, no global admin escalation, atomic/idempotent self-enrollment, independent seeds, roster lock, sample bots and invite-only compatibility.');
}finally{db.close();rmSync(directory,{recursive:true,force:true});}
